pub fn checker_step(
    r00000000: u32,
) -> [u32; 0x00000008_usize] {
    let r00000001: u32 = 0x00000000_u32;
    let r00000002: u32 = 0x00000000_u32;
    let r00000003: u32 = 0x00000000_u32;
    let r00000004: u32 = r00000000 >> 0x0000001d_u32;
    let r00000005: u32 = r00000000 >> 0x00000015_u32;
    let r00000006: u32 = 0x000000ff_u32;
    let r00000007: u32 = r00000005 & r00000006;
    let r00000008: u32 = r00000000 >> 0x0000000d_u32;
    let r00000009: u32 = 0x000000ff_u32;
    let r0000000a: u32 = r00000008 & r00000009;
    let r0000000b: u32 = r00000000 >> 0x00000005_u32;
    let r0000000c: u32 = 0x000000ff_u32;
    let r0000000d: u32 = r0000000b & r0000000c;
    let r0000000e: u32 = r00000000.rotate_right(0x0000001d_u32);
    let r0000000f: u32 = 0xfffffff8_u32;
    let r00000010: u32 = r0000000e & r0000000f;
    let r00000011: u32 = 0x000000ff_u32;
    let r00000012: u32 = r00000010 & r00000011;
    [r00000001, r00000002, r00000003, r00000004, r00000007, r0000000a, r0000000d, r00000012]
}
